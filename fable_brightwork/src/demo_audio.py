#!/usr/bin/env python3
"""Rough listening mock-up: head, two duo-solo choruses, head out.

Writes audio/Brightwork_mockup.mid and, if fluidsynth + a soundfont + ffmpeg are
available, audio/Brightwork_mockup.mp3. The rhythm section (bass, electric piano,
drums) is generated by simple rules; it is there for context, not as an arrangement.
"""
import random
import struct
import subprocess
import sys
from fractions import Fraction as F
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import engine as E  # noqa: E402
import music_head as H  # noqa: E402
import music_solo as S  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "audio"
PPQ = 480
SWING = F(13, 100)          # how late an off-beat eighth is played, in beats
SOUNDFONT = "/Applications/MuseScore 3.app/Contents/Resources/sound/MuseScore_General.sf3"
FLUIDSYNTH, FFMPEG = "/opt/homebrew/bin/fluidsynth", "/opt/homebrew/bin/ffmpeg"
rnd = random.Random(7)

CH_TPT, CH_GTR, CH_PNO, CH_BASS, CH_DR = 0, 1, 2, 3, 9
PROGRAM = {CH_TPT: 56, CH_GTR: 26, CH_PNO: 4, CH_BASS: 32}
VOLUME = {CH_TPT: 112, CH_GTR: 104, CH_PNO: 62, CH_BASS: 108, CH_DR: 84}
PAN = {CH_TPT: 50, CH_GTR: 80, CH_PNO: 58, CH_BASS: 64, CH_DR: 64}

# voicing intervals above the root (semitones), bottom to top
VOICING = {
    "maj7": [4, 9, 11, 14], "maj7#11": [4, 6, 11, 14], "m7": [3, 7, 10, 14], "7": [10, 14, 16, 21],
    "7#11": [10, 14, 16, 18], "7b9": [10, 13, 16, 21], "7sus": [10, 14, 17, 21], "7alt": [10, 15, 16, 20],
}
THIRD = {"m7": 3, "7sus": 5}


def swing(beat):
    return beat + SWING if beat % 1 == F(1, 2) else beat


class Song:
    def __init__(self):
        self.events = []        # (tick, order, bytes)

    def note(self, ch, pitch, start, dur, vel, jitter=0):
        t0 = int(round(swing(start) * PPQ)) + (rnd.randint(-jitter, jitter) if jitter else 0)
        t1 = int(round(swing(start + dur) * PPQ))
        t1 = max(t0 + 30, t1 - 14)
        vel = max(1, min(127, int(vel)))
        self.events.append((max(0, t0), 1, bytes([0x90 | ch, pitch, vel])))
        self.events.append((t1, 0, bytes([0x80 | ch, pitch, 0])))

    def write(self, path, bpm):
        def vlq(n):
            out = [n & 0x7F]
            while n > 0x7F:
                n >>= 7
                out.append((n & 0x7F) | 0x80)
            return bytes(reversed(out))

        data = b"\x00\xff\x51\x03" + struct.pack(">I", int(60_000_000 / bpm))[1:]
        for ch, prog in PROGRAM.items():
            data += b"\x00" + bytes([0xC0 | ch, prog])
        for ch in VOLUME:
            data += b"\x00" + bytes([0xB0 | ch, 7, VOLUME[ch]]) + b"\x00" + bytes([0xB0 | ch, 10, PAN[ch]])
            data += b"\x00" + bytes([0xB0 | ch, 91, 46])
        last = 0
        for tick, _, msg in sorted(self.events, key=lambda e: (e[0], e[1])):
            data += vlq(tick - last) + msg
            last = tick
        data += b"\x00\xff\x2f\x00"
        Path(path).write_bytes(b"MThd" + struct.pack(">IHHH", 6, 0, 1, PPQ) + b"MTrk"
                               + struct.pack(">I", len(data)) + data)


def melodic(song, ch, bars, start_bar, base_vel, lift=None, octave=0):
    """Play a parsed part; tied notes are merged. lift(bar_index) adds velocity."""
    pos, pending = F(start_bar * 4), None
    flat = [(bi, e) for bi, evs in enumerate(bars) for e in evs]
    for k, (bi, e) in enumerate(flat):
        dur = e.dur * 4
        if e.pitches:
            if pending and e.tied_in:
                pending[2] += dur
            else:
                pending = [pos, [E.midi(p) + octave for p in e.pitches], dur, bi]
            if not e.tie:
                st, pitches, d, b = pending
                nxt_rest = k + 1 >= len(flat) or flat[k + 1][1].is_rest
                length = d * F(92, 100) if d <= 1 else d - F(1, 8)
                if d == 1 and st % 1 == 0 and not nxt_rest:
                    length = d * F(4, 5)
                for p in pitches:
                    vel = base_vel + (p - 66) * 0.5 + rnd.randint(-4, 4)
                    if st % 1 != 0 and d >= 1:
                        vel += 7                      # pushed long notes
                    if lift:
                        vel += lift(b)
                    song.note(ch, p, st, length, vel, jitter=5)
                pending = None
        pos += dur


def root_pitch(root, lo):
    pc = (E.STEP_PC[root[0]] + root[1]) % 12
    return lo + (pc - lo) % 12


def rhythm_section(song, changes, start_bar, comp_vel=50, pads=(), final_hold=False):
    chords = E.parse_changes(changes)
    n = len(chords)
    roots = [[root_pitch(r, 34) for _, r, _ in row] for row in chords]
    for bi, row in enumerate(chords):
        b0 = F((start_bar + bi) * 4)
        nxt = roots[bi + 1][0] if bi + 1 < n else roots[0][0]
        hold = final_hold and bi >= n - 2
        # ---- bass: walking quarters
        if hold:
            if bi == n - 2:
                song.note(CH_BASS, roots[bi][0], b0, F(8), 92)
        elif len(row) == 1:
            r, q = roots[bi][0], row[0][2]
            third = r + THIRD.get(q, 4)
            fifth = r + 7 if r + 7 <= 50 else r - 5
            line = [r, third, fifth, None] if bi % 2 == 0 else [r, fifth, third, None]
            line[3] = nxt + 1 if abs(line[2] - (nxt + 1)) <= abs(line[2] - (nxt - 1)) else nxt - 1
            for k, p in enumerate(line):
                song.note(CH_BASS, p, b0 + k, F(9, 10), 96 if k == 0 else 86 + rnd.randint(-4, 4))
        else:
            r1, r2 = roots[bi]
            line = [r1, r2 + 1 if r1 > r2 else r2 - 1, r2, nxt + 1 if r2 >= nxt else nxt - 1]
            for k, p in enumerate(line):
                song.note(CH_BASS, p, b0 + k, F(9, 10), 96 if k % 2 == 0 else 86)
        # ---- electric piano comping
        def chord(root, qual, at, dur, vel):
            base = root_pitch(root, 48)
            notes = [base + iv for iv in VOICING[qual]]
            while notes[0] > 62:
                notes = [x - 12 for x in notes]
            while notes[0] < 52:
                notes = [x + 12 for x in notes]
            for p in notes:
                song.note(CH_PNO, p, b0 + at, dur, vel + rnd.randint(-3, 3))

        if hold:
            if bi == n - 2:
                chord(row[0][1], row[0][2], F(0), F(8), comp_vel + 8)
        elif len(row) == 2:
            chord(row[0][1], row[0][2], F(0), F(5, 4), comp_vel)
            chord(row[1][1], row[1][2], F(2), F(5, 4), comp_vel)
        elif bi in pads:
            chord(row[0][1], row[0][2], F(0), F(7, 2), comp_vel - 4)
        else:
            pattern = [[(F(0), F(5, 4)), (F(3, 2), F(1))], [(F(3, 2), F(1)), (F(3), F(3, 4))],
                       [(F(1, 2), F(1)), (F(5, 2), F(5, 4))], [(F(0), F(1)), (F(5, 2), F(1))]][bi % 4]
            for at, dur in pattern:
                chord(row[0][1], row[0][2], at, dur, comp_vel)
        # ---- drums
        if hold:
            if bi == n - 2:
                song.note(CH_DR, 49, b0, F(4), 84)
                song.note(CH_DR, 36, b0, F(1), 70)
            continue
        for at, vel in ((0, 66), (1, 82), (F(3, 2), 56), (2, 68), (3, 82), (F(7, 2), 56)):
            song.note(CH_DR, 51, b0 + at, F(1, 2), vel + rnd.randint(-4, 4))
        for at in (1, 3):
            song.note(CH_DR, 44, b0 + at, F(1, 2), 72)
        song.note(CH_DR, 36, b0, F(1, 2), 38)
        if bi % 8 == 0:
            song.note(CH_DR, 49, b0, F(2), 70)
        if bi % 4 == 1:
            song.note(CH_DR, 38, b0 + F(7, 2), F(1, 4), 46)
        if bi % 4 == 3:
            song.note(CH_DR, 38, b0 + F(3, 2), F(1, 4), 40)
            song.note(CH_DR, 38, b0 + F(7, 2), F(1, 4), 52)
        if bi % 8 == 7:
            for at, vel in ((F(5, 2), 50), (3, 58), (F(7, 2), 66)):
                song.note(CH_DR, 38, b0 + at, F(1, 4), vel)


def main():
    song = Song()
    for k in range(4):                                   # count-off
        song.note(CH_DR, 37, F(k), F(1, 2), 90 if k == 0 else 74)
    head = E.parse_part(H.HEAD)
    tpt, gtr = E.parse_part(S.TRUMPET), E.parse_part(S.GUITAR)
    out_src = H.HEAD[:30] + ["c''1~", "c''1~", "c''1"]
    head_out = E.parse_part(out_src)
    out_changes = H.CHANGES[:31] + ["Fmaj7#11", "Fmaj7#11"]
    bridge_pads = {16, 17, 18, 19, 20, 21}

    bar = 1
    melodic(song, CH_TPT, head, bar, 86)
    rhythm_section(song, H.CHANGES, bar, comp_vel=54, pads=bridge_pads)
    bar += 32
    climax = lambda b: 9 if 48 <= b < 56 else 0          # noqa: E731
    melodic(song, CH_TPT, tpt, bar, 88, lift=climax)
    melodic(song, CH_GTR, gtr, bar, 88, lift=climax)
    rhythm_section(song, H.CHANGES, bar, comp_vel=42)
    rhythm_section(song, H.CHANGES, bar + 32, comp_vel=44)
    bar += 64
    melodic(song, CH_TPT, head_out, bar, 90)
    melodic(song, CH_GTR, head_out, bar, 80, octave=-12)
    rhythm_section(song, out_changes, bar, comp_vel=56, pads=bridge_pads, final_hold=True)

    OUT.mkdir(exist_ok=True)
    mid = OUT / "Brightwork_mockup.mid"
    song.write(mid, H.TEMPO)
    print("wrote", mid.name)
    if "--no-audio" in sys.argv or not (Path(SOUNDFONT).exists() and Path(FLUIDSYNTH).exists()):
        return
    wav = Path("/tmp/brightwork_mockup.wav")
    subprocess.run([FLUIDSYNTH, "-ni", "-q", "-g", "0.7", "-r", "44100", "-F", str(wav), SOUNDFONT, str(mid)],
                   check=True)
    subprocess.run([FFMPEG, "-y", "-loglevel", "error", "-i", str(wav), "-codec:a", "libmp3lame", "-q:a", "4",
                    str(OUT / "Brightwork_mockup.mp3")], check=True)
    print("wrote Brightwork_mockup.mp3")


if __name__ == "__main__":
    main()
